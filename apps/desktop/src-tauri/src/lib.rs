//! Desktop shell for Caneca Quest.
//!
//! The game backend (FastAPI) is bundled as a sidecar executable. On launch we pick a
//! free loopback port, generate a per-launch bearer token, start the sidecar with them,
//! wait for its health check and only then open the window, injecting the address and
//! token into the page. Other local programs cannot drive the API without the token.
//! The webview gets no Tauri IPC permissions: the UI talks to the backend over HTTP only.

use std::io::{Read, Write};
use std::net::{SocketAddr, TcpListener, TcpStream};
use std::path::PathBuf;
use std::process::{Child, Command, Stdio};
use std::sync::Mutex;
use std::time::{Duration, Instant};

use tauri::{Manager, RunEvent, WebviewUrl, WebviewWindowBuilder};

struct Sidecar(Mutex<Option<Child>>);

fn free_port() -> std::io::Result<u16> {
    Ok(TcpListener::bind("127.0.0.1:0")?.local_addr()?.port())
}

fn random_token() -> String {
    let mut bytes = [0u8; 32];
    getrandom::fill(&mut bytes).expect("OS random source unavailable");
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// Minimal HTTP probe (no extra dependencies): true when /api/health answers 200.
fn healthy(port: u16) -> bool {
    let addr = SocketAddr::from(([127, 0, 0, 1], port));
    let Ok(mut stream) = TcpStream::connect_timeout(&addr, Duration::from_millis(300)) else {
        return false;
    };
    let _ = stream.set_read_timeout(Some(Duration::from_millis(800)));
    let request = format!("GET /api/health HTTP/1.1\r\nHost: 127.0.0.1:{port}\r\nConnection: close\r\n\r\n");
    if stream.write_all(request.as_bytes()).is_err() {
        return false;
    }
    let mut head = [0u8; 16];
    matches!(stream.read(&mut head), Ok(n) if n >= 12 && &head[9..12] == b"200")
}

fn sidecar_path() -> Option<PathBuf> {
    let dir = std::env::current_exe().ok()?.parent()?.to_path_buf();
    let name = if cfg!(windows) { "caneca-server.exe" } else { "caneca-server" };
    let candidate = dir.join(name);
    candidate.exists().then_some(candidate)
}

fn start_backend(app: &tauri::AppHandle) -> Result<(String, String), String> {
    // Development: point at an already running backend (e.g. `uv run caneca-server`).
    if let Ok(url) = std::env::var("CANECA_DESKTOP_BACKEND_URL") {
        return Ok((url, std::env::var("CANECA_API_TOKEN").unwrap_or_default()));
    }
    let exe = sidecar_path().ok_or("sidecar não encontrado ao lado do executável")?;
    let data_dir = app.path().app_data_dir().map_err(|e| e.to_string())?;
    let cache_dir = app.path().app_cache_dir().map_err(|e| e.to_string())?;
    std::fs::create_dir_all(&data_dir).map_err(|e| e.to_string())?;
    std::fs::create_dir_all(&cache_dir).map_err(|e| e.to_string())?;
    let port = free_port().map_err(|e| e.to_string())?;
    let token = random_token();

    let child = Command::new(exe)
        .arg("--port")
        .arg(port.to_string())
        .arg("--data-dir")
        .arg(&data_dir)
        .env("CANECA_HOST", "127.0.0.1")
        .env("CANECA_API_TOKEN", &token)
        // Lets the sidecar shut itself down if this process dies without cleaning up.
        .env("CANECA_PARENT_PID", std::process::id().to_string())
        // The one-file sidecar unpacks itself; some systems mount /tmp as noexec.
        .env("TMPDIR", &cache_dir)
        .env("TMP", &cache_dir)
        .env("TEMP", &cache_dir)
        .stdin(Stdio::null())
        .spawn()
        .map_err(|e| format!("falha ao iniciar o servidor: {e}"))?;
    app.state::<Sidecar>().0.lock().unwrap().replace(child);

    let deadline = Instant::now() + Duration::from_secs(40);
    while Instant::now() < deadline {
        if healthy(port) {
            return Ok((format!("http://127.0.0.1:{port}"), token));
        }
        std::thread::sleep(Duration::from_millis(150));
    }
    Err("o servidor do jogo não respondeu a tempo".into())
}

fn stop_backend(app: &tauri::AppHandle) {
    if let Some(mut child) = app.state::<Sidecar>().0.lock().unwrap().take() {
        let _ = child.kill();
        let _ = child.wait();
    }
}

fn js_string(value: &str) -> String {
    // Values are generated by us (URL and hex token), but escape defensively anyway.
    value.replace('\\', "\\\\").replace('\'', "\\'")
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let app = tauri::Builder::default()
        .manage(Sidecar(Mutex::new(None)))
        .setup(|app| {
            let handle = app.handle().clone();
            let (base_url, token) = start_backend(&handle).map_err(|e| {
                stop_backend(&handle);
                Box::<dyn std::error::Error>::from(e)
            })?;
            let script = format!(
                "window.__CANECA_RUNTIME__ = Object.freeze({{ baseUrl: '{}', token: '{}' }});",
                js_string(&base_url),
                js_string(&token)
            );
            WebviewWindowBuilder::new(app, "main", WebviewUrl::App("index.html".into()))
                .title("Caneca Quest — A Jornada de uma Caneca")
                .inner_size(1280.0, 840.0)
                .min_inner_size(380.0, 600.0)
                .initialization_script(&script)
                .build()?;
            Ok(())
        })
        .build(tauri::generate_context!())
        .expect("error while building Caneca Quest");

    app.run(|handle, event| {
        if let RunEvent::Exit = event {
            stop_backend(handle);
        }
    });
}
